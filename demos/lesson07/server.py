# Import libraries
# WebAPI related
from fastapi import FastAPI, Depends, HTTPException, Response, status
# Database related
from sqlalchemy.orm import Session # to manage db connections and sessions
# db modules
from db.connection import get_db # to be able to pass a db connection to the route functions
from db.models import Project
# Pydantic schemas 
from schemas import ProjectRead, ProjectCreate, ProjectUpdate

# Declare the app object
app = FastAPI(title="Project Tracker API", version="1.0.0", description="A simple API for managing school projects.")

# Define route handlers (endpoints) for the API
# GET endpoint to retrieve all projects from the database
# GET /api/projects
@app.get("/api/projects", response_model=list[ProjectRead], description="Retrieves all projects from the database.")
# Dependency injection to get a database session for the request
# The db parameter is automatically provided by FastAPI using the get_db function defined in db/connection.py
def list_projects(db: Session = Depends(get_db)):
    return db.query(Project).all() 

# POST /api/projects
@app.post("/api/projects", 
          response_model=ProjectRead, 
          description="Creates a new project in the database.",
          status_code=status.HTTP_201_CREATED) # 201 means created successfully with no response body expected
def create_project(payload: ProjectCreate, db: Session = Depends(get_db)) -> Project:
    new_project = Project(**payload.model_dump()) # unpack the payload into the Project model
    db.add(new_project) # adds to the db session but does not commit, not yet persisted in the actual db
    db.commit() # commit the changes to the database, now the new project is persisted in the db
    db.refresh(new_project) # refreshes the object with data from the db (autogenerated fields like id, created_at, updated_at)
    return new_project

# PUT /api/projects/{project_id} > request body contains the updated data in JSON
@app.put("/api/projects/{project_id}",
         response_model=ProjectRead, 
          description="Updates an existing project in the database.",
          status_code=status.HTTP_200_OK)
def update_project(project_id: int, payload: ProjectUpdate, db: Session = Depends(get_db)) -> Project:
    # Find the project by id, if not found, raise a 404 error
    project = db.get(Project, project_id)
    if project is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Project with id {project_id} not found")

    # Update the project with the new data
    # PUT is full update so all updatable fields must be provided in the request body even if there is no change to them
    # Pydantic will take care of the validation of the data types and constraints, so we can safely assign the values 
    project.name = payload.name
    project.due_date = payload.due_date
    project.status = payload.status
    project.description = payload.description

    # Commit the changes to the database and return the updated project
    db.commit()
    db.refresh(project)
    # returns the refreshed/updated project object
    return project

# DELETE /api/projects/{project_id}
@app.delete("/api/projects/{project_id}", 
            description="Deletes an existing project from the database.",
            status_code=status.HTTP_204_NO_CONTENT) 
def delete_project(project_id: int, db: Session = Depends(get_db)) -> Response:
    # Find the project by id, if not found, raise a 404 error
    project = db.get(Project, project_id)
    if project is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Project with id {project_id} not found")

    # Delete the project from the database
    db.delete(project)
    # Commit the changes to the database and return a 204 No Content response
    db.commit()
    return Response(status_code=status.HTTP_204_NO_CONTENT)